// Generates web/src/element-ids.d.ts: every id in web/index.html mapped to its element's DOM type,
// so byId("…") is typed and an id that is not in the page fails the type check.
// `node scripts/element-types.mjs --check` fails when the committed file is out of date.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, ".."),
  target = resolve(root, "web/src/element-ids.d.ts");
const types = {
  a: "HTMLAnchorElement",
  button: "HTMLButtonElement",
  canvas: "HTMLCanvasElement",
  dialog: "HTMLDialogElement",
  form: "HTMLFormElement",
  img: "HTMLImageElement",
  input: "HTMLInputElement",
  label: "HTMLLabelElement",
  select: "HTMLSelectElement",
  textarea: "HTMLTextAreaElement",
};
const html = await readFile(resolve(root, "web/index.html"), "utf8"),
  ids = new Map();
for (const match of html.matchAll(/<([a-z][a-z0-9-]*)\b[^>]*?\sid="([^"]+)"/g)) {
  const [, tag, id] = match;
  if (ids.has(id)) throw new Error(`duplicate id in web/index.html: ${id}`);
  ids.set(id, types[tag] || "HTMLElement");
}
const output = `// Generated by scripts/element-types.mjs from web/index.html. Do not edit.
export interface ElementIds {
${[...ids]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, type]) => `  ${JSON.stringify(id)}: ${type};`)
  .join("\n")}
}
`;
if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) {
    console.error("web/src/element-ids.d.ts is out of date: run node scripts/element-types.mjs");
    process.exit(1);
  }
} else await writeFile(target, output);
console.log(`${ids.size} element ids`);
